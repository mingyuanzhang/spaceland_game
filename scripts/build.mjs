import { readFile, writeFile } from 'node:fs/promises';

// The modules have no dependencies. Their ordered bundle also works from a
// file:// URL, where browsers refuse to load ES modules.
export async function browserSource() {
  const files = ['world.js', 'game.js', 'render.js', 'app.js'];
  const sources = await Promise.all(files.map(file => readFile(new URL(`../src/${file}`, import.meta.url), 'utf8')));
  return sources.map((source, i) => `// src/${files[i]}\n${source.replace(/^import .*?;\s*$/gm, '').replace(/^export /gm, '')}`).join('\n\n');
}

if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) {
  const source = await browserSource();
  await writeFile(new URL('../app.bundle.js', import.meta.url), `// Generated by npm run build. Edit src/ files.\n(() => {\n'use strict';\n${source}\n})();\n`);
  console.log('Built app.bundle.js — ready to open index.html directly.');
}
